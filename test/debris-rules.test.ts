import assert from 'node:assert/strict';
import {WALLS,geometry,transform} from '../src/game';
import {SoloGame} from '../src/solo-game';

const game=new SoloGame(0,()=>0);
game.choose(0,4);game.choose(1,4);
const wall=WALLS.findIndex(w=>w.edges.some(([q,k])=>q===40&&k===1));
assert.ok(wall>=0);
game.positions[0]=40;game.act(0,4+wall);
assert.equal(game.manualAvailable,false);
assert.equal(game.legal(1).includes(4+wall),false);
const overlap=WALLS.findIndex((w,id)=>id!==wall&&w.edges.some(([q,k])=>WALLS[wall].edges.some(([x,y])=>q===x&&k===y)));
assert.equal(game.legal(1).includes(4+overlap),false);
game.turn=0;assert.equal(game.legal(0).includes(4+wall),false);
game.positions[0]=40;game.act(0,116+wall);
assert.equal(game.snapshot(0).debris.length,3);
const mirrored=WALLS[transform(wall+4,1)-4];
assert.ok(game.snapshot(1).debris.every(({q,k})=>mirrored.edges.some(([x,y])=>x===q&&y===k)));
game.turn=0;game.positions[0]=40;game.act(0,4+wall);
assert.equal(game.positions[0],31);
assert.ok(game.moves(0).includes(1));
const partial=WALLS.findIndex((w,id)=>id!==wall&&w.orientation===WALLS[wall].orientation&&w.edges.filter(([q,k])=>WALLS[wall].edges.some(([x,y])=>q===x&&k===y)).length===2);
game.turn=0;game.positions[0]=40;assert.ok(game.legal(0).includes(4+partial));game.act(0,4+partial);
const board=geometry(game.walls,game.boundary,game.debrisEdges);
for(const [q,k] of WALLS[partial].edges)assert.equal(board.blocked[q][k],!game.debrisEdges.has(`${q}:${k}`));
const stuck=new SoloGame(0);stuck.choose(0,4);stuck.choose(1,4);
const internals=stuck as unknown as {owned:number[][]};internals.owned[1].fill(1);for(let w=0;w<WALLS.length;w++)stuck.walls.add(w);
assert.deepEqual(stuck.legal(0),[4]);assert.equal(stuck.canPass,true);stuck.act(0,4);assert.equal(stuck.turn,1);
console.log('残骸、重叠与移动优先级检查通过');
